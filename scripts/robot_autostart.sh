#!/usr/bin/env bash
set -euo pipefail

# Optional autostart for the robot-side stack, as a single systemd unit that
# runs `ros2 launch mini_robot robot.launch.py` at boot. Run this on the
# Raspberry Pi.
#
#   bash scripts/robot_autostart.sh on          run now + start at every boot
#   bash scripts/robot_autostart.sh off         stop now + do not start at boot
#   bash scripts/robot_autostart.sh start       start now, boot setting unchanged
#   bash scripts/robot_autostart.sh stop        stop now, boot setting unchanged
#   bash scripts/robot_autostart.sh restart     restart now
#   bash scripts/robot_autostart.sh status      what is installed/enabled/running
#   bash scripts/robot_autostart.sh logs [-f]   the unit's journal
#   bash scripts/robot_autostart.sh preview     print the unit file, install nothing
#   bash scripts/robot_autostart.sh install     write the unit, leave it off
#   bash scripts/robot_autostart.sh uninstall   remove the unit entirely
#
# Nothing here changes the rest of the project. The unit is generated into
# /etc/systemd/system (no repo file is touched), and with it off the manual
# workflow is exactly what it was: `ros2 launch mini_robot robot.launch.py` in
# a login shell. With it on, run `off` first before launching by hand - two
# processes cannot share the Arduino and LiDAR ports.

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd -- "$SCRIPT_DIR/.." && pwd)"

UNIT="mini-robot.service"
UNIT_PATH="/etc/systemd/system/$UNIT"

# Run under sudo and $USER is root; the robot's user is the one who invoked it.
SERVICE_USER="${SUDO_USER:-${USER:-$(id -un)}}"
USER_HOME="$(getent passwd "$SERVICE_USER" | cut -d: -f6)"
USER_HOME="${USER_HOME:-$HOME}"
ROS_DISTRO="${ROS_DISTRO:-humble}"
WORKSPACE_DIR="${WORKSPACE_DIR:-$USER_HOME/ros2_ws}"
ROS_DOMAIN="${ROS_DOMAIN_ID:-31}"

if ! command -v systemctl >/dev/null 2>&1; then
  echo "ERROR: systemctl not found; this machine does not use systemd." >&2
  exit 1
fi

unit_text() {
  cat <<UNIT
# GENERATED by scripts/robot_autostart.sh on $(date -Is) ($(hostname)).
# Paths, user and ROS_DOMAIN_ID are per-machine, so this is not tracked in the
# repo. Re-run the script rather than hand-editing it; 'uninstall' removes it.
[Unit]
Description=mini robot ROS 2 bringup (robot.launch.py)
Documentation=file://$REPO_ROOT/README.md
After=network-online.target
Wants=network-online.target
# DDS binds its interfaces at startup, so starting before the network is up
# gives a stack the workstation cannot see.
StartLimitIntervalSec=300
StartLimitBurst=10

[Service]
Type=simple
User=$SERVICE_USER
# The Arduino and the LiDAR are both dialout-group tty devices.
SupplementaryGroups=dialout
WorkingDirectory=$REPO_ROOT
Environment=HOME=$USER_HOME
Environment=ROS_DISTRO=$ROS_DISTRO
Environment=WORKSPACE_DIR=$WORKSPACE_DIR
Environment=ROS_DOMAIN_ID=$ROS_DOMAIN
Environment=ROS_LOCALHOST_ONLY=0
ExecStart=$REPO_ROOT/scripts/robot_bringup.sh
Restart=on-failure
RestartSec=5
# ros2 launch shuts its nodes down on SIGINT (SIGTERM leaves them orphaned),
# and KillMode=mixed sends it to the launcher only, not to the whole cgroup.
KillSignal=SIGINT
KillMode=mixed
TimeoutStopSec=20

[Install]
WantedBy=multi-user.target
UNIT
}

require_installed() {
  if [ ! -f "$UNIT_PATH" ]; then
    echo "ERROR: $UNIT is not installed yet. Run:" >&2
    echo "  bash scripts/robot_autostart.sh install" >&2
    exit 1
  fi
}

warn_if_hand_started() {
  if pgrep -f 'serial_bridge|coin_d6_lidar' >/dev/null 2>&1 &&
     ! systemctl is-active --quiet "$UNIT"; then
    echo "NOTE: the stack looks like it is already running outside systemd."
    echo "      Stop that shell's 'ros2 launch' first, or the unit will just"
    echo "      stand aside — it cannot share the serial ports."
  fi
}

do_install() {
  [ -x "$REPO_ROOT/scripts/robot_bringup.sh" ] ||
    { echo "ERROR: $REPO_ROOT/scripts/robot_bringup.sh is missing or not executable" >&2; exit 1; }
  [ -f "/opt/ros/$ROS_DISTRO/setup.bash" ] ||
    { echo "ERROR: /opt/ros/$ROS_DISTRO/setup.bash not found. Run bootstrap_robot_stack.sh pi first." >&2; exit 1; }
  [ -f "$WORKSPACE_DIR/install/setup.bash" ] ||
    { echo "ERROR: $WORKSPACE_DIR/install/setup.bash not found. Build the workspace first." >&2; exit 1; }

  local tmp
  tmp="$(mktemp)"
  unit_text > "$tmp"
  sudo install -m 0644 -o root -g root "$tmp" "$UNIT_PATH"
  rm -f "$tmp"
  sudo systemctl daemon-reload
  echo "Installed $UNIT_PATH"
}

case "${1:-status}" in
  install)
    do_install
    echo "The unit is installed but still OFF. Turn it on with:"
    echo "  bash scripts/robot_autostart.sh on"
    ;;

  preview)
    unit_text
    ;;

  on)
    # A repo that has moved leaves the installed unit pointing at a path that
    # no longer exists, and the failure looks like a ROS problem. Re-running
    # 'on' should just fix it.
    if [ ! -f "$UNIT_PATH" ]; then
      do_install
    elif ! grep -qxF "ExecStart=$REPO_ROOT/scripts/robot_bringup.sh" "$UNIT_PATH"; then
      echo "The installed unit runs a different path; rewriting it for $REPO_ROOT."
      do_install
    fi
    warn_if_hand_started
    sudo systemctl enable --now "$UNIT"
    echo "Autostart ON: running now and at every boot."
    echo "Watch it come up with: bash scripts/robot_autostart.sh logs -f"
    ;;

  off)
    require_installed
    sudo systemctl disable --now "$UNIT"
    echo "Autostart OFF: stopped, and it will not start at boot."
    echo "Manual launch is unaffected: ros2 launch mini_robot robot.launch.py"
    ;;

  start|restart)
    require_installed
    warn_if_hand_started
    sudo systemctl "$1" "$UNIT"
    echo "Bringup ${1}ed for this boot; the boot setting is unchanged."
    ;;

  stop)
    require_installed
    sudo systemctl stop "$UNIT"
    echo "Bringup stopped for this boot; the boot setting is unchanged."
    ;;

  status)
    printf '%-16s %s\n' "repo" "$REPO_ROOT"
    printf '%-16s %s\n' "user" "$SERVICE_USER"
    printf '%-16s %s\n' "workspace" "$WORKSPACE_DIR"
    printf '%-16s %s\n' "ROS_DOMAIN_ID" "$ROS_DOMAIN"
    if [ -f "$UNIT_PATH" ]; then
      printf '%-16s %s\n' "unit file" "$UNIT_PATH"
      printf '%-16s %s\n' "at boot" "$(systemctl is-enabled "$UNIT" 2>/dev/null || echo disabled)"
      printf '%-16s %s\n' "right now" "$(systemctl is-active "$UNIT" 2>/dev/null || echo inactive)"
      if ! grep -qxF "ExecStart=$REPO_ROOT/scripts/robot_bringup.sh" "$UNIT_PATH"; then
        printf '%-16s %s\n' "WARNING" "the unit runs a different path than this repo; re-run 'on'"
      fi
      echo
      systemctl --no-pager --lines=0 status "$UNIT" 2>/dev/null | sed -n '1,6p' || true
    else
      printf '%-16s %s\n' "unit file" "not installed"
    fi
    echo
    if pgrep -f 'serial_bridge|coin_d6_lidar' >/dev/null 2>&1; then
      echo "Serial nodes are running (systemd's, or a hand-started 'ros2 launch')."
    else
      echo "No serial nodes are running."
    fi
    ;;

  logs)
    require_installed
    shift
    journalctl -u "$UNIT" --no-pager -n 200 "$@"
    ;;

  uninstall)
    sudo systemctl disable --now "$UNIT" 2>/dev/null || true
    sudo rm -f "$UNIT_PATH"
    sudo systemctl daemon-reload
    sudo systemctl reset-failed "$UNIT" 2>/dev/null || true
    echo "Removed $UNIT_PATH. Nothing else was touched."
    ;;

  -h|--help|help)
    sed -n '4,24p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
    ;;

  *)
    echo "Unknown command: $1" >&2
    echo "Try: $0 --help" >&2
    exit 1
    ;;
esac
